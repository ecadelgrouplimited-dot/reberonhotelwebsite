// Regenerates apps/{web,admin}/lib/fonts.ts from FONT_CATALOG. Run from the repo root after building @reberon/contracts:
//   pnpm --filter @reberon/contracts build && node scripts/gen-fonts.mjs
import { writeFileSync } from 'node:fs';
const { FONT_CATALOG } = await import(process.cwd() + '/packages/contracts/dist/typography.js');
const ident = (f) => f.replace(/ /g, '_');
const id = (k) => 'f_' + k.replace(/-/g, '_');
function gen(preload) {
  const imports = [...new Set(FONT_CATALOG.map((f) => ident(f.family)).concat(['JetBrains_Mono']))].sort();
  let out = `/* Generated by scripts/gen-fonts.mjs from FONT_CATALOG (packages/contracts/src/typography.ts) — do not edit by hand.
 * Every font is self-hosted by next/font. Only the defaults are preloaded; the
 * others download only on pages whose chosen typography uses them. */
import { ${imports.join(', ')} } from 'next/font/google';

`;
  for (const f of FONT_CATALOG) {
    const opts = [`subsets: ['latin']`, `variable: '--ff-${f.key}'`, `display: 'swap'`, `preload: ${preload.includes(f.key)}`];
    if (f.fixedWeight) opts.push(`weight: '${f.fixedWeight}'`);
    if (f.kind === 'serif') opts.push(`style: ['normal', 'italic']`);
    if (f.key === 'fraunces') opts.push(`axes: ['SOFT', 'opsz']`);
    out += `const ${id(f.key)} = ${ident(f.family)}({ ${opts.join(', ')} });\n`;
  }
  out += `const f_mono = JetBrains_Mono({ subsets: ['latin'], variable: '--font-mono-face', display: 'swap', preload: false });\n\n`;
  out += `/** Class names that define every --ff-* variable (put on <html>). */\nexport const FONT_CLASSES = [${FONT_CATALOG.map((f) => id(f.key) + '.variable').join(', ')}, f_mono.variable].join(' ');\n`;
  return out;
}
writeFileSync('apps/web/lib/fonts.ts', gen(['fraunces', 'inter']));
writeFileSync('apps/admin/lib/fonts.ts', gen(['plus-jakarta-sans', 'inter']));
console.log('ok', FONT_CATALOG.length);
